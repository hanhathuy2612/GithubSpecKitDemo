-- 002-user-auth (plan.md › Design Summary › Data)
ALTER TABLE user_account ADD COLUMN session_version INT DEFAULT 0 NOT NULL;

CREATE TABLE registration_token (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(254)             NOT NULL,
    token_hash     CHAR(64)                 NOT NULL,
    issued_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at        TIMESTAMP WITH TIME ZONE,
    invalidated_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_registration_token_hash UNIQUE (token_hash)
);
CREATE INDEX ix_registration_token_email ON registration_token (email);

CREATE TABLE auth_session (
    id                  VARCHAR(36)              NOT NULL PRIMARY KEY,
    account_id          BIGINT                   NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    absolute_expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at          TIMESTAMP WITH TIME ZONE,
    revoke_reason       VARCHAR(32),
    CONSTRAINT fk_auth_session_account FOREIGN KEY (account_id) REFERENCES user_account (id)
);
CREATE INDEX ix_auth_session_account ON auth_session (account_id);

CREATE TABLE refresh_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(36)              NOT NULL,
    token_hash CHAR(64)                 NOT NULL,
    issued_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    rotated_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_token_session FOREIGN KEY (session_id) REFERENCES auth_session (id)
);
CREATE INDEX ix_refresh_token_session ON refresh_token (session_id);
